import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, type Locator, type Page, type TestInfo } from '@playwright/test';

export const CORPUS_DIR = fileURLToPath(new URL('../corpus/', import.meta.url));

export interface CorpusEntry {
  file: string;
  expect: 'open' | 'error' | 'password';
  pages?: number;
  error?: 'empty' | 'not-pdf' | 'damaged';
  password?: string;
  rotations?: number[];
  search?: { term: string; matches: number; pages: number[] };
  note?: string;
  // Real-world files only: where it came from and its checksum when it was
  // checked blank, so a filled-in copy can't slip into the public repo.
  source?: string;
  sha256?: string;
}

const readManifest = (name: string): CorpusEntry[] =>
  JSON.parse(readFileSync(new URL(`../corpus/${name}`, import.meta.url), 'utf8')).files;

// corpus.json is generated by scripts/make-corpus.mjs; real-world.json is
// maintained by hand.
export const realWorldCorpus = readManifest('real-world.json');
export const corpus: CorpusEntry[] = [...readManifest('corpus.json'), ...realWorldCorpus];

export function corpusEntry(file: string): CorpusEntry {
  const entry = corpus.find((e) => e.file === file);
  if (!entry) throw new Error(`${file} is not in corpus.json`);
  return entry;
}

export const corpusPath = (file: string) => CORPUS_DIR + file;

export function isMobile(testInfo: TestInfo): boolean {
  return testInfo.project.name.startsWith('mobile');
}

export async function gotoApp(page: Page) {
  await page.goto('./');
  await expect(page.getByTestId('empty-state')).toBeVisible();
}

// Opens a corpus file through the real file picker input.
export async function openCorpusFile(page: Page, file: string) {
  await page.getByTestId('file-input').setInputFiles(corpusPath(file));
}

export async function expectDocumentOpen(page: Page, pages: number) {
  await expect(page.getByTestId('app')).toHaveAttribute('data-doc-pages', String(pages));
  await expect(page.getByTestId('page')).toHaveCount(pages);
  await expectPageRendered(page, 0);
}

// A page counts as rendered once its bitmap has decoded.
export async function expectPageRendered(page: Page, index: number) {
  const img = page.locator(`[data-page-index="${index}"] [data-testid="page-image"]`);
  await expect(img).toBeVisible();
  await expect.poll(() => img.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true);
}

export async function currentPageNumber(page: Page): Promise<number> {
  return Number(await page.getByTestId('page-input').inputValue());
}

// Phones type text fields through the input bar (FieldInputBar); desktop
// browsers type into the field on the page. These work for both.
export async function typeInto(page: Page, field: Locator, value: string) {
  const tag = await field.evaluate((el) => el.tagName);
  if (tag !== 'BUTTON') {
    await field.fill(value);
    return;
  }
  await field.click();
  await expect(page.getByTestId('field-input-bar')).toBeVisible();
  await page.getByTestId('field-input').fill(value);
  await page.getByTestId('field-done').click();
  await expect(page.getByTestId('field-input-bar')).toHaveCount(0);
}

// The text a field shows: its value on desktop, its label text on phones.
// Date fields on phones show the formatted date, so compare the date's parts.
export async function expectFieldText(field: Locator, value: string) {
  const tag = await field.evaluate((el) => el.tagName);
  if (tag === 'BUTTON') {
    const iso = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
    await expect(field).toHaveText(iso ? `${iso[2]}/${iso[3]}/${iso[1]}` : value.replace(/\n/g, '\n'));
  } else {
    await expect(field).toHaveValue(value);
  }
}

// Whether text fields here are typed through the phone input bar.
export async function usesInputBar(page: Page): Promise<boolean> {
  return page.evaluate(() => matchMedia('(pointer: coarse)').matches);
}
